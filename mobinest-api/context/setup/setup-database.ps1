<#
.SYNOPSIS
  One-time MySQL setup for the MobiNest API (Windows PowerShell 5.1+).

.DESCRIPTION
  1. Creates the database (utf8mb4).
  2. Creates a least-privilege application user with a freshly generated random password.
  3. Writes <project>\config\application.properties (git-ignored) so Spring Boot can connect.

  Tables are NOT created here: Flyway creates them, and the sample catalogue is loaded,
  the first time the API starts.

  Re-running is safe. It rotates the app user's password and rewrites the config file,
  so restart the API afterwards.

.EXAMPLE
  # interactive (asks for the MySQL root password, input hidden)
  powershell -ExecutionPolicy Bypass -File context\setup\setup-database.ps1

.EXAMPLE
  # non-interactive (e.g. when an AI assistant runs it for you)
  powershell -ExecutionPolicy Bypass -File context\setup\setup-database.ps1 -RootPassword "<root password>"
#>
param(
    [string]$RootUser = 'root',
    [string]$RootPassword,
    [string]$DbHost = 'localhost',
    [int]$DbPort = 3306,
    [string]$DbName = 'mobinest',
    [string]$AppUser = 'mobinest_app',
    [string]$ConfigPath = (Join-Path $PSScriptRoot '..\..\config\application.properties')
)

$ErrorActionPreference = 'Stop'

if ($DbName -notmatch '^[A-Za-z0-9_]+$' -or $AppUser -notmatch '^[A-Za-z0-9_]+$') {
    throw 'DbName and AppUser may contain only letters, digits and underscores.'
}

# Locate mysql.exe (PATH first, then the default MySQL 8.x install folders)
$mysql = (Get-Command mysql.exe -ErrorAction SilentlyContinue).Source
if (-not $mysql) {
    $mysql = Get-ChildItem 'C:\Program Files\MySQL\MySQL Server *\bin\mysql.exe' -ErrorAction SilentlyContinue |
        Sort-Object FullName -Descending | Select-Object -First 1 -ExpandProperty FullName
}
if (-not $mysql) { throw 'mysql.exe not found. Install MySQL Server 8.x first (see context\README.md).' }

if (-not $RootPassword) {
    $secure = Read-Host "MySQL password for '$RootUser'" -AsSecureString
    $RootPassword = [Runtime.InteropServices.Marshal]::PtrToStringAuto(
        [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure))
}

# Random 24-char password (no quotes or backslashes, so it is safe inside SQL and .properties)
$alphabet = [char[]]'abcdefghijkmnpqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789'
$bytes = New-Object byte[] 24
[Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
$appPassword = -join ($bytes | ForEach-Object { $alphabet[$_ % $alphabet.Length] })

$sql = @"
CREATE DATABASE IF NOT EXISTS $DbName CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
CREATE USER IF NOT EXISTS '$AppUser'@'localhost' IDENTIFIED BY '$appPassword';
ALTER USER '$AppUser'@'localhost' IDENTIFIED BY '$appPassword';
GRANT SELECT, INSERT, UPDATE, DELETE, CREATE, ALTER, DROP, INDEX, REFERENCES ON $DbName.* TO '$AppUser'@'localhost';
FLUSH PRIVILEGES;
"@

$env:MYSQL_PWD = $RootPassword   # avoids putting the password on the command line
try {
    $sql | & $mysql -h $DbHost -P $DbPort -u $RootUser --batch
    if ($LASTEXITCODE -ne 0) { throw "mysql exited with code $LASTEXITCODE (wrong root password?)" }
} finally {
    Remove-Item Env:MYSQL_PWD -ErrorAction SilentlyContinue
}

$configDir = Split-Path $ConfigPath -Parent
New-Item -ItemType Directory -Force -Path $configDir | Out-Null
$props = @"
# Local secrets - git-ignored. Spring Boot loads ./config/application.properties automatically.
# Generated by context/setup/setup-database.ps1
spring.datasource.url=jdbc:mysql://${DbHost}:${DbPort}/${DbName}?serverTimezone=UTC&useSSL=false&allowPublicKeyRetrieval=true
spring.datasource.username=$AppUser
spring.datasource.password=$appPassword
"@
[IO.File]::WriteAllText((Resolve-Path $configDir).Path + '\' + (Split-Path $ConfigPath -Leaf), $props,
    (New-Object Text.UTF8Encoding $false))

Write-Host "OK: database '$DbName' and user '$AppUser' are ready."
Write-Host "Config written to $ConfigPath"
Write-Host 'Next: mvnw.cmd spring-boot:run   (Flyway creates the tables and loads the sample catalogue)'
