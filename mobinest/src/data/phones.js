export let PHONES = ALL_PHONES.filter((p) => ACTIVE_BRAND_IDS.includes(p.brand))

export let PHONE_MAP = Object.fromEntries(PHONES.map((p) => [p.id, p]))

/** Replace the catalogue with phones from the API (call after setBrands). */
export function setPhones(list) {
  PHONES = list.filter((p) => ACTIVE_BRAND_IDS.includes(p.brand)).map((p) => ({ tags: [], conditions: ['new'], ...p }))
  PHONE_MAP = Object.fromEntries(PHONES.map((p) => [p.id, p]))
}

export const getPhone = (id) => PHONE_MAP[id]
