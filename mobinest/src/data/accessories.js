export function setAccessoryCategories(list) {
  const icons = Object.fromEntries(ACCESSORY_CATEGORIES.map((c) => [c.id, c.icon]))
  ACCESSORY_CATEGORIES = list.map((c) => ({ icon: icons[c.id] || 'box', ...c }))
  ACCESSORY_CATEGORY_MAP = Object.fromEntries(ACCESSORY_CATEGORIES.map((c) => [c.id, c]))
}

export function setAccessories(list) {
  ACCESSORIES = list.map((a) => ({ colors: [], compatibleBrands: ['all'], features: [], ...a }))
  ACCESSORY_MAP = Object.fromEntries(ACCESSORIES.map((a) => [a.id, a]))
}

export const getAccessory = (id) => ACCESSORY_MAP[id]
